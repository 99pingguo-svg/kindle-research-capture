/** Best guess from the product name, or 'その他'. */
export function guessCategory(name) {
  const s = String(name || '').normalize('NFKC');
  if (!s.trim()) return 'その他';
  return RULES.find(([, re]) => re.test(s))?.[0] || 'その他';
}
